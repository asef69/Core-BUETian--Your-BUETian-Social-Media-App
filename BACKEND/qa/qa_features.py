def items(r):
    d = getattr(r, "data", None)
    if isinstance(d, list): return d
    if isinstance(d, dict):
        for k in ("results", "posts", "products", "messages", "items", "data"):
            if isinstance(d.get(k), list): return d[k]
    return []
def txt(r): return json.dumps(getattr(r, "data", None), default=str)
def ok(r, *codes): return r.status_code in (codes or (200, 201))
def q1(sql, p=()):
    rows = DM.execute_query(sql, p); return rows[0] if rows else None
def S(area): return area

